const OFFSET = 500;

function normalizeDelays(absoluteTimes: number[]): number[] {
    if (absoluteTimes.length === 0) return [];

    const firstTime = absoluteTimes[0];
    const delays: number[] = [];
    delays.push(OFFSET);

    for (let i = 1; i < absoluteTimes.length; i++) {
        delays.push(absoluteTimes[i] - firstTime + OFFSET);
    }

    return delays;
}

