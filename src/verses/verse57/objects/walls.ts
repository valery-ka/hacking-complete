function createWallsCircle(
    count: number,
    step: number,
    radius: number,
    frames: number = 500,
    speed: number = 100,
    pool: number = 20,
): WallConfig[] {
    return Array.from({ length: count }, (_, i) => i * step).map((from) => ({
        type: "box",
        position: { x: 0, y: 5.45, z: 115 },
        size: { w: 1.5, h: 1.5, d: 1.5 },
        rotation: { x: 0, y: 0, z: 0 },
        color: { r: 0, g: 0, b: 0, a: 0 },
        trigger: { pool: pool, spawn: { on_start: true, on_update: false } },
        solid: true,
        is_lava: true,
        animation: {
            name: "circle",
            plane: "xz",
            radius: radius,
            frames: frames,
            speed: speed,
            delay: [10000, 0],
            from: from,
        },
        not_cast_shadow: true,
    }));
}
