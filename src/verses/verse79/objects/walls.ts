const wall = (
    p: { x: number; y: number; z: number },
    s: { w: number; h: number; d: number },
): WallConfig => ({
    trigger: { pool: 500, spawn: { on_start: true, on_update: false } },
    type: "box-dark",
    position: p,
    size: s,
    rotation: { x: 0, y: 0, z: 0 },
    color: WALLS_COLOR,
    solid: true,
    is_lava: false,
    // disable_physics: true,
    // not_mergeable: true,
});

const floatWall = (
    p: { x: number; y: number; z: number },
    s: { w: number; h: number; d: number },
    type: "box" | "box-light" | "box-dark" | "box-ui" | "box-base" | "box-lawa" = "box",
): WallConfig => ({
    trigger: { pool: 500, spawn: { on_start: true, on_update: false } },
    type: type === "box-lawa" ? "box" : type,
    position: p,
    size: s,
    rotation: { x: 0, y: 0, z: 0 },
    color: WALLS_COLOR,
    solid: true,
    is_lava: type === "box-lawa",
    disable_physics: true,
    not_mergeable: true,
    animation: {
        name: "bob",
        axes: {
            y: {
                amplitude: getRandomNumber(2, 5),
                speed: getRandomNumber(5, 10),
            },
        },
        frames: getRandomNumber(100, 200),
        from: getRandomNumber(0, 200),
    },
});

function getRandomNumber(min: number, max: number) {
    return Math.floor(Math.random() * (max - min + 1)) + min;
}

